import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const {version}=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('Release version must be x.y.z');
if (process.env.GITHUB_REF_TYPE==='tag' && process.env.GITHUB_REF_NAME!==`v${version}`) throw new Error('Tag and package version must match');
if (!fs.existsSync(path.join(root,'dist/index.html'))) throw new Error('Run npm run build before packaging');
if (execFileSync('git',['status','--porcelain'],{cwd:root,encoding:'utf8'}).trim()) throw new Error('Commit all source changes before packaging a release');
const output=path.join(root,'release');fs.mkdirSync(output,{recursive:true});
const staging=fs.mkdtempSync(path.join(output,'.package-'));
const name=`harpscore-${version}-web`;
const bundle=path.join(staging,name);fs.mkdirSync(bundle);
fs.cpSync(path.join(root,'dist'),path.join(bundle,'dist'),{recursive:true});
fs.copyFileSync(path.join(root,'tools/release-server.mjs'),path.join(bundle,'serve.mjs'));
fs.copyFileSync(path.join(root,'LICENSE'),path.join(bundle,'LICENSE'));
fs.copyFileSync(path.join(root,`docs/releases/v${version}.md`),path.join(bundle,'RELEASE-NOTES.md'));
fs.writeFileSync(path.join(bundle,'START.cmd'),'@echo off\r\ncd /d "%~dp0"\r\nnode serve.mjs\r\npause\r\n');
fs.writeFileSync(path.join(bundle,'使用说明.txt'),`HarpScore ${version}\n\n需要Node.js 24或更新版本。无需npm install。\nWindows：双击START.cmd，再在浏览器打开 http://127.0.0.1:4178\n其他平台：在本目录执行 node serve.mjs，再打开同一地址。\nCtrl+C停止；端口被占用时可用PORT环境变量指定其他端口。\n\n个人曲谱和收藏保存在浏览器，绑定当前网址与端口。升级前请导出个人库备份，并沿用同一地址和浏览器。不要依赖隐私窗口保存数据。\n部署静态站点时只需上传dist目录。不要直接双击dist/index.html。\n此版本为Web应用，不包含Windows EXE或音频播放。\n`);
const commit=execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim();
fs.writeFileSync(path.join(bundle,'version.json'),JSON.stringify({version,commit},null,2)+'\n');
const archive=path.join(output,`${name}.tar.gz`);
execFileSync('tar',['-czf',archive,'-C',staging,name]);
const sha=createHash('sha256').update(fs.readFileSync(archive)).digest('hex');
fs.writeFileSync(path.join(output,'SHA256SUMS.txt'),`${sha}  ${path.basename(archive)}\n`);
console.log(`Packaged ${path.basename(archive)} (${fs.statSync(archive).size} bytes), commit ${commit}`);
